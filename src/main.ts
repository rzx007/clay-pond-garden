import * as THREE from 'three';
import {OrbitControls} from 'three/addons/controls/OrbitControls.js';
import {addTerrain} from './terrain';
import {addWater} from './water';
import {addPlants} from './plants';
import {addAnimals} from './animals';

const scene=new THREE.Scene();scene.background=new THREE.Color('#eee8dc');
const camera=new THREE.OrthographicCamera();camera.position.set(0,13,9);camera.lookAt(0,0,0);
const renderer=new THREE.WebGLRenderer({antialias:true,alpha:false,powerPreference:'high-performance'});
renderer.setPixelRatio(Math.min(devicePixelRatio,1.75));renderer.shadowMap.enabled=true;renderer.shadowMap.type=THREE.VSMShadowMap;renderer.outputColorSpace=THREE.SRGBColorSpace;renderer.toneMapping=THREE.ACESFilmicToneMapping;renderer.toneMappingExposure=1.0;
renderer.domElement.setAttribute('aria-label','柔和黏土质感的微缩池塘花园，三条鱼在荷叶与鸭子间缓缓游动');document.body.appendChild(renderer.domElement);
const controls=new OrbitControls(camera,renderer.domElement);
controls.enableDamping=true;
controls.dampingFactor=.075;
controls.rotateSpeed=.65;
controls.panSpeed=.7;
controls.zoomSpeed=.65;
controls.minPolarAngle=THREE.MathUtils.degToRad(20);
controls.maxPolarAngle=THREE.MathUtils.degToRad(65);
controls.minAzimuthAngle=-Math.PI/2;
controls.maxAzimuthAngle=Math.PI/2;
controls.minZoom=.75;
controls.maxZoom=2.5;
controls.screenSpacePanning=false;
controls.maxTargetRadius=3;
controls.mouseButtons={LEFT:THREE.MOUSE.ROTATE,MIDDLE:THREE.MOUSE.DOLLY,RIGHT:THREE.MOUSE.PAN};
controls.touches={ONE:THREE.TOUCH.ROTATE,TWO:THREE.TOUCH.DOLLY_PAN};
controls.update();
controls.saveState();
renderer.domElement.addEventListener('dblclick',()=>controls.reset());
renderer.domElement.setAttribute('aria-label','微缩池塘花园。左键拖动旋转，右键拖动平移，滚轮缩放，双击恢复初始视角。');
scene.add(new THREE.HemisphereLight('#fff4dc','#b6a6c6',2.3));
const sun=new THREE.DirectionalLight('#fff4dc',1.8);sun.position.set(-5,9,-4);sun.castShadow=true;sun.shadow.mapSize.set(2048,2048);sun.shadow.camera.left=-9;sun.shadow.camera.right=9;sun.shadow.camera.top=8;sun.shadow.camera.bottom=-8;sun.shadow.normalBias=.025;sun.shadow.bias=-.0002;sun.shadow.radius=5;sun.shadow.blurSamples=12;scene.add(sun);
const floor=new THREE.Mesh(new THREE.PlaneGeometry(200,200),new THREE.MeshStandardMaterial({color:'#eee8dc',roughness:1}));floor.rotation.x=-Math.PI/2;floor.position.y=-.33;floor.receiveShadow=true;scene.add(floor);
addTerrain(scene);const plants=addPlants(scene);const animals=addAnimals(scene);const water=addWater(scene);
const cloud=new THREE.Group();cloud.position.set(3.25,2.5,-3.7);
const cloudMat=new THREE.MeshStandardMaterial({color:'#fff8eb',roughness:1});
for(const [x,y,z,r] of [[-.53,0,0,.32],[-.24,.06,0,.38],[.1,.14,0,.46],[.47,.23,0,.34],[.05,-.13,.04,.3]]){const m=new THREE.Mesh(new THREE.SphereGeometry(r,28,20),cloudMat);m.position.set(x,y,z);m.scale.z=.65;cloud.add(m);}scene.add(cloud);
function resize(){const aspect=innerWidth/innerHeight;const h=Math.max(8.9,14.2/aspect);camera.left=-h*aspect/2;camera.right=h*aspect/2;camera.top=h/2;camera.bottom=-h/2;camera.updateProjectionMatrix();renderer.setSize(innerWidth,innerHeight);}
window.addEventListener('resize',resize);resize();
const reduced=matchMedia('(prefers-reduced-motion: reduce)').matches;
const clock=new THREE.Clock();renderer.setAnimationLoop(()=>{const t=reduced?0:clock.getElapsedTime();plants.update(t);animals.update(t);water.update(t);controls.update();renderer.render(scene,camera);});
